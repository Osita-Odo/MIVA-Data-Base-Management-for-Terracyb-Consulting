#!/usr/bin/env bash
# Measures every query before and after the optimisations in indexes.sql.
# Saves full EXPLAIN (ANALYZE, BUFFERS) plans and a timing summary.
# Usage: ./run_benchmark.sh [database]      (default database: ead)
# Stop on any error (-e), on unset variables (-u) and on a failure inside a pipe.
set -euo pipefail
DB="${1:-ead}"
RUNS=5      # timed runs per query; the median is reported
cd "$(dirname "$0")"
# Every psql session looks in schema "ead" first, so queries need no prefix.
export PGOPTIONS="-c search_path=ead"
# -X ignores ~/.psqlrc so personal settings cannot change the output;
# ON_ERROR_STOP makes a SQL error stop the script instead of being skipped.
PSQL=(psql -d "$DB" -X -q -v ON_ERROR_STOP=1)

mkdir -p plans/before plans/after results

# Prints the median "Execution Time" (ms) of RUNS runs and saves the last plan.
measure () {
    local file="$1" out="$2" times=()
    local sql
    # Strip the final semicolon so the query can be wrapped in EXPLAIN (...)
    sql=$(sed 's/;[[:space:]]*$//' "$file")
    "${PSQL[@]}" -c "$sql" > /dev/null                       # warm the cache
    # EXPLAIN ANALYZE really executes the query and reports actual times;
    # BUFFERS adds how many pages came from memory (hit) or disk (read).
    for _ in $(seq "$RUNS"); do
        "${PSQL[@]}" -c "EXPLAIN (ANALYZE, BUFFERS) $sql" > "$out"
        # Keep only the number from the line "Execution Time: 12.345 ms"
        times+=("$(grep -oP 'Execution Time: \K[0-9.]+' "$out")")
    done
    # Median rather than mean: one slow run (another program busy) cannot skew it
    printf '%s\n' "${times[@]}" | sort -n | awk '{a[NR]=$1} END {print a[int((NR+1)/2)]}'
}

# Names the main access path used on the finding table (or the materialised view).
plan_node () {
    local n
    # Prefer an index-based access path on the finding table if the plan has one;
    # otherwise report the sequential scan.
    n=$(grep -oE '((Index Only Scan|Index Scan) using|Bitmap Index Scan on) (idx_finding|idx_mv|finding)[a-z_]*' "$1" | head -1 || true)
    [[ -z "$n" ]] && n=$(grep -oE 'Seq Scan on (finding|mv_mttr|control_assessment|engagement)' "$1" | head -1 || true)
    echo "${n:-see plan}"
}

echo "1/3  Baseline: dropping optimisations"
"${PSQL[@]}" -f drop_indexes.sql

# Associative arrays: query name -> median time in ms
declare -A before after
for f in queries/*.sql; do
    q=$(basename "$f" .sql)
    before[$q]=$(measure "$f" "plans/before/$q.txt")
    echo "     $q  ${before[$q]} ms"
done

echo "2/3  Creating optimisations (indexes.sql)"
"${PSQL[@]}" -f indexes.sql

for f in queries/*.sql; do
    q=$(basename "$f" .sql)
    after[$q]=$(measure "$f" "plans/after/$q.txt")
    echo "     $q  ${after[$q]} ms"
done
mv_time=$(measure q2b_mttr_from_materialised_view.sql plans/after/q2b_mttr_from_materialised_view.txt)
echo "     q2b_mttr_from_materialised_view  $mv_time ms"

echo "3/3  Writing results/timings.md"
{
    echo "# Query timings: before and after optimisation"
    echo
    echo "Generated by run_benchmark.sh on $(date "+%Y-%m-%d %H:%M"), PostgreSQL $(psql -d "$DB" -X -tAc "SHOW server_version" | cut -d" " -f1)."
    echo "Median of $RUNS runs of EXPLAIN (ANALYZE, BUFFERS), warm cache. Times in milliseconds."
    echo
    echo "| Query | Before (ms) | After (ms) | Speed-up | Plan node before | Plan node after |"
    echo "| --- | ---: | ---: | ---: | --- | --- |"
    for f in queries/*.sql; do
        q=$(basename "$f" .sql)
        b=${before[$q]}; a=${after[$q]}
        # Q2 is optimised by replacing it with the materialised view, so its
        # "after" figure is the time of q2b, not of the original query.
        if [[ "$q" == q2_* ]]; then a=$mv_time; fi
        speed=$(awk -v b="$b" -v a="$a" 'BEGIN { if (a > 0) printf "%.1fx", b / a; else print "n/a" }')
        nb=$(plan_node "plans/before/$q.txt")
        plan_after="plans/after/$q.txt"
        if [[ "$q" == q2_* ]]; then plan_after="plans/after/q2b_mttr_from_materialised_view.txt"; fi
        na=$(plan_node "$plan_after")
        echo "| $q | $b | $a | $speed | ${nb:-see plan} | ${na:-see plan} |"
    done
    echo
    echo "Q2 'after' is the materialised view (q2b). Full plans are in plans/before and plans/after."
} > results/timings.md

cat results/timings.md
